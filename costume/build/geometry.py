def sode_top():
    w = 24
    holes = [(x, 5.8) for x in SODE_COLS(w)] + [(7, 2.6), (17, 2.6)]
    return dict(key="sode_top", title="سردوشی — صفحه‌ی بالا", en="Sode top plate",
                w=w, h=7, path=f"M0,1.2 Q12,-0.8 24,1.2 L24,7 L0,7 Z", holes=holes)


def sode_lame(i, w):
    c = (w + 1) / 2
    cols = [c - (w / 2 - 2.5), c - 4.5, c + 4.5, c + (w / 2 - 2.5)]
    holes = [(x, 1.2) for x in cols] + [(x, 4.8) for x in cols]
    return dict(key=f"sode_l{i}", title=f"سردوشی — تیغه‌ی {i}", en=f"Sode lame {i}",
                w=w + 1, h=6.6,
                path=f"M0.5,0 L{w+0.5},0 L{w+1},6 Q{(w+1)/2},6.8 0,6 Z", holes=holes)


def sode_pieces():
    return [sode_top(), sode_lame(1, 24), sode_lame(2, 25), sode_lame(3, 26)]


